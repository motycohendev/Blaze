        public static int EvaluatePieceSquareTables(Board board)
        {
            int eval = 0;

            for (int i = 0; i < 12; i++)
            {
                ulong Bitboard = board.PiecesBitboards[i];
                int pieceColor = i < 6 ? 1 : -1; // White pieces are indexed 0-5, black pieces are indexed 6-11
                int pieceType = i % 6;
                while (Bitboard != 0)
                {
                    int squareIndex = BitboardHelper.PopLSB(ref Bitboard);
                    int tableIndex = pieceColor == 1 ? squareIndex ^ 56 : squareIndex; // Flip the index for black pieces
                    int pieceValue = SquareTables[pieceType][tableIndex];
                    // Add or subtract the piece value based on the color
                    eval += pieceValue * pieceColor;
                }
            }
            return eval;
        }
