        public static (int mgScore, int egScore) EvaluatePieceSquareTables(Board board)
        {
            int mgScore = 0;
            int egScore = 0;
            for (int i = 0; i < 12; i++)
            {
                ulong bitboard = board.PiecesBitboards[i];
                int pieceColor = i < 6 ? 1 : -1; // White pieces are indexed 0-5, black pieces are indexed 6-11
                while (bitboard != 0)
                {
                    int squareIndex = BitboardHelper.PopLSB(ref bitboard);
                    int square = i < 6 ? squareIndex ^ 56 : squareIndex; // Flip the square index for black pieces
                    mgScore += pieceColor * EarlySquareTables[i%6][square];
                    egScore += pieceColor * LateSquareTables[i%6][square];
                }
            }
            return (mgScore, egScore);
        }
